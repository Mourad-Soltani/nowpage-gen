#!/usr/bin/env python3
"""
NowPage Generator
A minimal CLI tool to generate a beautiful, single-file "Now Page".

Signature: Mourad.Soltani
"""

import argparse
import os
from datetime import datetime

HTML_TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{title} — Now</title>
  <style>
    :root {{
      --bg: #0f0f0f;
      --fg: #e8e8e8;
      --accent: #3b82f6;
      --muted: #888;
    }}
    @media (prefers-color-scheme: light) {{
      :root {{
        --bg: #fafafa;
        --fg: #111;
        --accent: #2563eb;
        --muted: #666;
      }}
    }}
    body {{
      font-family: system-ui, -apple-system, sans-serif;
      background: var(--bg);
      color: var(--fg);
      max-width: 680px;
      margin: 4rem auto;
      padding: 0 1.5rem;
      line-height: 1.6;
    }}
    h1 {{ font-size: 2rem; margin-bottom: 0.5rem; }}
    .subtitle {{ color: var(--muted); font-size: 0.95rem; margin-bottom: 2rem; }}
    section {{ margin-bottom: 2rem; }}
    h2 {{ font-size: 1.2rem; border-bottom: 1px solid var(--muted); padding-bottom: 0.3rem; }}
    ul {{ padding-left: 1.2rem; }}
    footer {{
      margin-top: 3rem;
      font-size: 0.85rem;
      color: var(--muted);
      text-align: center;
    }}
    a {{ color: var(--accent); text-decoration: none; }}
    a:hover {{ text-decoration: underline; }}
  </style>
</head>
<body>
  <h1>{name}'s Now Page</h1>
  <p class="subtitle">What I'm focused on right now — {date}</p>

  <section>
    <h2>Currently</h2>
    <p>{currently}</p>
  </section>

  <section>
    <h2>Projects</h2>
    <ul>
      {projects_html}
    </ul>
  </section>

  <section>
    <h2>Location</h2>
    <p>{location}</p>
  </section>

  <footer>
    Generated by NowPage Gen · Signature: Mourad.Soltani · <a href="https://nownownow.com">nownownow.com</a>
  </footer>
</body>
</html>
"""


def generate_html(name: str, currently: str, projects: list[str], location: str, title: str | None = None) -> str:
    """Generate the Now Page HTML string."""
    if title is None:
        title = f"{name} — Now"
    date = datetime.now().strftime("%B %Y")
    projects_html = "\n".join(f"      <li>{p.strip()}</li>" for p in projects if p.strip())
    return HTML_TEMPLATE.format(
        title=title,
        name=name,
        date=date,
        currently=currently,
        projects_html=projects_html or "<li>No active projects listed.</li>",
        location=location,
    )


def main():
    parser = argparse.ArgumentParser(description="Generate a beautiful single-file Now Page")
    parser.add_argument("--name", required=True, help="Your name")
    parser.add_argument("--currently", required=True, help="What you are focused on now")
    parser.add_argument("--projects", required=True, help="Comma-separated list of current projects")
    parser.add_argument("--location", required=True, help="Your location")
    parser.add_argument("--output", default="now.html", help="Output HTML file path")
    args = parser.parse_args()

    projects = [p.strip() for p in args.projects.split(",") if p.strip()]
    html = generate_html(args.name, args.currently, projects, args.location)

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(html)

    print(f"Now page written to {args.output}")
    print("Open it in a browser or host it statically.")


if __name__ == "__main__":
    main()
